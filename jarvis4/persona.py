def detect_mode(text: str, replying_to_jarvis: bool = False) -> Mode:
    """ANGRY when the owner swears or complains at Jarvis; WORK when he asks for something; else CHAT."""
    text = text or ""
    swears = len(SWEAR.findall(text))
    if swears and (YOU.search(text) or replying_to_jarvis or swears >= 2):
        return Mode.ANGRY
    if swears and CORRECTION.search(text):
        return Mode.ANGRY
    if QUESTION.search(text) and text.strip().endswith("?") and len(text) < 120:
        return Mode.CHAT
    return Mode.WORK if TASK.search(text) else Mode.CHAT


def is_correction(text: str) -> bool:
    return bool(CORRECTION.search(text or "")) or (bool(SWEAR.search(text or "")) and bool(YOU.search(text or "")))


def wants_thinking(text: str) -> bool:
    return bool(THINK.search(text or ""))


def finalize(text: str) -> str:
    """Telegram shows **bold** and ### as they are: a person never writes like that."""
    text = text.strip()
    text = re.sub(r"^(?:джарвис|jarvis)\s*[:—-]\s*", "", text, flags=re.I)
    text = re.sub(r"```[a-z]*\n?|```", "", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text, flags=re.S)
    text = re.sub(r"__(.+?)__", r"\1", text, flags=re.S)
    text = re.sub(r"(?m)^\s{0,3}#{1,6}\s*", "", text)
    text = text.replace("`", "")
    return re.sub(r"\n{3,}", "\n\n", text).strip()


def chunks(text: str, limit: int = 3900) -> list[str]:
    """Pieces that fit one Telegram message, cut at paragraphs or sentences."""
    out = []
    while len(text) > limit:
        cut = max(text.rfind("\n\n", 0, limit), text.rfind("\n", 0, limit), text.rfind(". ", 0, limit) + 1)
        cut = cut if cut > limit // 2 else limit
        out.append(text[:cut].strip())
        text = text[cut:].strip()
    return out + ([text] if text else [])
